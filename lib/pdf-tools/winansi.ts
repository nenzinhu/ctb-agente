export type Fonte = 'Helvetica' | 'Helvetica-Bold';

// Codes 0x80-0x9F that Windows-1252 assigns to typographic characters.
const ESPECIAIS: Record<string, number> = {
  '€': 0x80, '‚': 0x82, 'ƒ': 0x83, '„': 0x84, '…': 0x85, '†': 0x86, '‡': 0x87, 'ˆ': 0x88, '‰': 0x89,
  'Š': 0x8a, '‹': 0x8b, 'Œ': 0x8c, 'Ž': 0x8e, '‘': 0x91, '’': 0x92, '“': 0x93, '”': 0x94, '•': 0x95,
  '–': 0x96, '—': 0x97, '˜': 0x98, '™': 0x99, 'š': 0x9a, '›': 0x9b, 'œ': 0x9c, 'ž': 0x9e, 'Ÿ': 0x9f,
};

/**
 * One character → its WinAnsi byte. Characters outside the encoding fall
 * back to their base letter ("ẽ" → "e"), then to "?".
 */
export function codigoWinAnsi(caractere: string): number {
  const code = caractere.codePointAt(0) ?? 0x3f;
  if (code === 0x09 || code === 0xa0) return 0x20;
  if ((code >= 0x20 && code <= 0x7e) || (code >= 0xa1 && code <= 0xff)) return code;
  const especial = ESPECIAIS[caractere];
  if (especial) return especial;
  const base = caractere.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  if (base && base !== caractere) return codigoWinAnsi(base[0]);
  return 0x3f;
}

/**
 * @returns The text as WinAnsi bytes (one byte per character)
 */
export function codificarWinAnsi(texto: string): Uint8Array {
  return Uint8Array.from(Array.from(texto.normalize('NFC')), codigoWinAnsi);
}

/**
 * Width of a text in points at the given size.
 */
export function larguraTexto(texto: string, fonte: Fonte, tamanho: number): number {
  const tabela = fonte === 'Helvetica' ? HELVETICA : HELVETICA_BOLD;
  let total = 0;
  for (const byte of codificarWinAnsi(texto)) total += tabela[byte - 32] ?? 556;
  return (total * tamanho) / 1000;
}
